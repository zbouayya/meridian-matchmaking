"""The spec report: one line per spec in docs/SPECS.md, with what happened on this run.

Written to build/spec-report.md at the end of every test session and appended to the CI job
summary, so the state of each requirement is read off a page rather than out of a log.
"""

from __future__ import annotations

from collections import Counter
from pathlib import Path

import pytest

from tests.spec.registry import REPO_ROOT, Spec, load_specs

REPORT_FILE = REPO_ROOT / "build" / "spec-report.md"

Outcome = tuple[str, str, str]  # test id, outcome, reason when skipped
OUTCOMES = pytest.StashKey[dict[str, list[Outcome]]]()
SCORER_OUTPUT = pytest.StashKey[str]()

_LABELS = {
    "failed": "FAILED",
    "passed": "passed",
    "waiting": "waiting for results",
    "not-run": "not run in this session",
    "pending": "pending — component not built",
    "manual": "manual",
}
_ORDER = ("failed", "passed", "waiting", "not-run", "pending", "manual")


def status_of(spec: Spec, outcomes: list[Outcome]) -> tuple[str, str]:
    """(bucket, text shown in the report) for one spec."""
    if spec.mode in ("pending", "manual"):
        return spec.mode, _LABELS[spec.mode]
    failed = [o for o in outcomes if o[1] == "failed"]
    passed = [o for o in outcomes if o[1] == "passed"]
    skipped = [o for o in outcomes if o[1] == "skipped"]
    if failed:
        return "failed", f"**FAILED** — {len(failed)} of {len(outcomes)} tests"
    if passed:
        note = f" ({len(skipped)} skipped)" if skipped else ""
        return "passed", f"passed — {len(passed)} tests{note}"
    if skipped:
        return "waiting", f"waiting — {skipped[0][2] or 'skipped'}"
    return "not-run", _LABELS["not-run"]


def tally(specs: list[Spec], outcomes: dict[str, list[Outcome]]) -> Counter[str]:
    return Counter(status_of(spec, outcomes.get(spec.id, []))[0] for spec in specs)


def summary_line(counts: Counter[str]) -> str:
    parts = [f"{counts[bucket]} {_LABELS[bucket]}" for bucket in _ORDER if counts[bucket]]
    return f"{sum(counts.values())} specs: " + ", ".join(parts)


def _cell(text: str) -> str:
    return text.replace("|", "/")


def render(outcomes: dict[str, list[Outcome]], scorer_output: str | None) -> str:
    specs = load_specs()
    counts = tally(specs, outcomes)
    lines = [
        "# Spec report",
        "",
        "Generated by the test run from `docs/SPECS.md`. Do not edit.",
        "",
        f"**{summary_line(counts)}**",
        "",
        "| ID | Requirement | Mode | This run |",
        "|---|---|---|---|",
    ]
    for spec in specs:
        _, text = status_of(spec, outcomes.get(spec.id, []))
        mode = spec.mode + (" (partial)" if spec.partial else "")
        requirement = spec.requirement
        if len(requirement) > 150:
            requirement = requirement[:147].rstrip() + "…"
        lines.append(f"| {spec.id} | {_cell(requirement)} | {mode} | {_cell(text)} |")
    failures = [
        f"- `{test}` ({spec_id})"
        for spec_id, runs in sorted(outcomes.items())
        for test, outcome, _ in runs
        if outcome == "failed"
    ]
    if failures:
        lines += ["", "## Failing tests", "", *failures]
    if scorer_output:
        lines += ["", "## Scorer output", "", "```", scorer_output.rstrip(), "```"]
    return "\n".join(lines) + "\n"


def write(config: pytest.Config, path: Path = REPORT_FILE) -> Counter[str]:
    outcomes = config.stash.get(OUTCOMES, {})
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(outcomes, config.stash.get(SCORER_OUTPUT, None)), encoding="utf-8")
    return tally(load_specs(), outcomes)
